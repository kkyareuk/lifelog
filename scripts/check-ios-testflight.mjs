import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {generateKeyPairSync,verify} from 'node:crypto';
import {makeToken} from './ios-asc-status.mjs';
const read=path=>readFileSync(new URL(`../${path}`,import.meta.url),'utf8');
const workflow=read('.github/workflows/ios-testflight.yml');
const request=JSON.parse(read('.github/ios-testflight-request.json'));
const release=JSON.parse(read('ios-release.json'));
assert.equal(request.version,release.version);
// Preparing local fixes must not mutate the explicit upload trigger.
if(process.argv.includes('--prepared'))assert.ok(request.build<=release.build);
else assert.equal(request.build,release.build);
assert.equal(request.internalOnly,true);assert.equal(request.uploadToTestFlight,true);assert.equal(request.submitForReview,false);
assert.equal(release.appStoreReady,false);
assert.match(workflow,/branches: \[dev\]/);
assert.match(workflow,/paths: \[\.github\/ios-testflight-request\.json\]/);
assert.match(workflow,/github\.ref == 'refs\/heads\/dev'/);
assert.match(workflow,/contents: read/);assert.match(workflow,/persist-credentials: false/);
assert.match(workflow,/runs-on: macos-15\s/);assert.match(workflow,/timeout-minutes: 30/);
assert.match(workflow,/retention-days: 3/);assert.match(workflow,/testflight-reports\/\*\.json/);
assert.doesNotMatch(workflow,/pull_request|schedule:|macos-.*(?:large|xlarge)|path:.*(?:\.ipa|\.p12|\.p8|\.mobileprovision)/);
const script=read('scripts/ios-testflight.mjs');
assert.match(script,/testFlightInternalTestingOnly:true/);
assert.match(script,/manageAppVersionAndBuildNumber:false/);
assert.match(script,/delete-keychain/);
assert.match(script,/API_PRIVATE_KEYS_DIR/);
assert.doesNotMatch(script,/usesNonExemptEncryption\s*[:=]\s*false|betaAppReviewSubmissions|appStoreVersionReleaseRequests/);
const statusWorkflow=read('.github/workflows/ios-testflight-status.yml');
assert.match(statusWorkflow,/paths: \[\.github\/ios-testflight-status-request\.json\]/);
assert.match(statusWorkflow,/timeout-minutes: 5/);
assert.doesNotMatch(statusWorkflow,/IOS_DISTRIBUTION|IOS_PROVISION|ios-testflight\.mjs|npm ci/);
assert.match(read('scripts/ios-asc-status.mjs'),/INTERNAL_ONLY,APP_STORE_ELIGIBLE/);
const {privateKey,publicKey}=generateKeyPairSync('ec',{namedCurve:'prime256v1'});
const token=makeToken({ASC_KEY_ID:'FAKEKEY',ASC_ISSUER_ID:'fake-issuer',ASC_PRIVATE_KEY:privateKey.export({type:'pkcs8',format:'pem'})},1000);
const parts=token.split('.');
assert.equal(parts.length,3);
assert.equal(JSON.parse(Buffer.from(parts[1],'base64url')).exp,1600);
assert.equal(verify('sha256',Buffer.from(parts.slice(0,2).join('.')),{key:publicKey,dsaEncoding:'ieee-p1363'},Buffer.from(parts[2],'base64url')),true);
console.log('PASS internal TestFlight: explicit dev request, bounded runner, internal-only export, no store submission, secret isolation, JWT signing.');

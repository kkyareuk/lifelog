import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {roomPermissionMarkup,roomResidents,readRoomPermissionEditor,ROOM_PERMISSION_COPY} from "../room-permissions.js";
import {homeEditorCopy,homeFurnitureDrawer,homeInformationMarkup} from "../home-editor-ui.js";
const state={order:["a","b","outside"],characters:{a:{id:"a",name:"A",residences:[{homeId:"h"}]},b:{id:"b",name:"B",residences:[{homeId:"h"}]},outside:{id:"outside",name:"Outside",residences:[{homeId:"other"}]}}};
const home={id:"h",rooms:{living:{name:"Living",floor:1,type:"living"}},pets:[{id:"cat",name:"<Cat>"}]};
assert.deepEqual(roomResidents(state,"h").map(c=>c.id),["a","b"]);
for(const uiLanguage of ["ko","en","ja"]){
 const c=ROOM_PERMISSION_COPY[uiLanguage],markup=roomPermissionMarkup(home,{ownerCharacterIds:["a"],accessMode:"selected"}, {...state,uiLanguage});
 assert.deepEqual(Object.keys(c).sort(),Object.keys(ROOM_PERMISSION_COPY.ko).sort());
 assert.equal((markup.match(/name="ownerCharacterIds"/g)||[]).length,2);
 assert.ok(!markup.match(/name="ownerCharacterIds" value="outside"/));
 assert.ok(markup.includes('name="accessCharacterIds" value="outside"'));
 assert.ok(markup.includes('name="accessPetIds" value="cat"')&&markup.includes("&lt;Cat&gt;"));
 for(const key of ["all","ownersOnly","delivery","repair","cats","custom"])assert.ok(markup.includes(c[key]));
 if(uiLanguage!=="ko")assert.ok(!/[가-힣]/.test(Object.values(c).join("")));
 const drawer=homeFurnitureDrawer(home,uiLanguage);
 assert.equal((drawer.match(/name="furnitureTheme"/g)||[]).length,1);
 assert.ok(drawer.includes(homeEditorCopy(uiLanguage).defaultTheme));
}
const inputs={ownerAll:{checked:true},accessMode:{value:"selected"},accessCustom:{value:"Guest\nGuest\n  Technician  \n"}};
const checked={ownerCharacterIds:["a","b"],accessGroups:["delivery","cats"],accessCharacterIds:["outside"],accessPetIds:["cat"]};
const root={querySelector:selector=>inputs[selector.match(/name="([^"]+)"/)[1]],querySelectorAll:selector=>(checked[selector.match(/name="([^"]+)"/)[1]]||[]).map(value=>({value}))};
const result=readRoomPermissionEditor(root);
assert.equal(result.ownerMode,"all");assert.equal(result.accessMode,"selected");
assert.deepEqual(result.ownerCharacterIds,["a","b"]);assert.deepEqual(result.accessCustom,["Guest","Technician"]);
assert.deepEqual(JSON.parse(JSON.stringify(result)),result,"permission settings survive storage round-trip");
const read=file=>readFileSync(new URL("../"+file,import.meta.url),"utf8");
const app=read("app.js"),css=read("home-editor-ui.css");
assert.ok(app.includes("...readRoomPermissionEditor(dialog)")&&app.includes("bindRoomPermissionEditor(dialog)"));
assert.ok(app.includes('class="room-editor-actions editor-save-actions"'));
assert.ok(read("views.js").includes("data-editor-save")&&app.includes('$$("[data-editor-save]")'));
assert.ok(read("dictionary.js").includes("data-dict-save"));
assert.ok(css.includes("background-size:cover!important"));
const drawerStyle=css.match(/\.home-furniture-drawer\{[^}]+/)[0];
assert.ok(!drawerStyle.includes("url("),"furniture drawer has no wood texture");
assert.ok(css.includes("grid-auto-columns:calc((100% - 24px)/4)"));
assert.ok(read("app.css").includes("html body #app .home.is-editing .room-furniture-item small{display:block}"));
console.log("PASS room editor 212: household-only multi-owners, everyone/owners/custom access settings, persistence, explicit saves, theme catalog, photo cover and ko/en/ja.");
